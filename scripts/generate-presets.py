#!/usr/bin/env python3
"""Embeds config/molly.*.json into Sources/Molly/Settings/Presets.swift.

The Settings window applies presets without needing the config files next to
the app bundle. A unit test checks the embedded copies match the files, so run
this after editing any of the three example configs.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = {
    "strict": ROOT / "config/molly.privacy-strict.json",
    "balanced": ROOT / "config/molly.example.json",
    "developer": ROOT / "config/molly.developer.json",
}
OUT = ROOT / "Sources/Molly/Settings/Presets.swift"


def main() -> int:
    parts = [
        "// Generated by scripts/generate-presets.py from config/*.json. Do not edit.",
        "import Foundation",
        "",
        "/// The three example configs, embedded so presets work from the app bundle.",
        "enum Presets {",
        "    static func json(_ preset: SettingsModel.Preset) -> String {",
        "        switch preset {",
    ]
    for name in FILES:
        parts.append(f"        case .{name}: return {name}")
    parts += ["        }", "    }", ""]
    for name, path in FILES.items():
        text = json.dumps(json.loads(path.read_text()), indent=2, sort_keys=True)
        parts.append(f'    static let {name} = #"""')
        parts.append(text)
        parts.append('"""#')
        parts.append("")
    parts.append("}")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
